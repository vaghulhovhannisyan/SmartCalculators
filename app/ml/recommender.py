"""Рекомендации материалов под контекст помещения.

Модуль работает по принципу экспертных правил (rule-based scoring):
для каждого типа помещения задан набор обязательных и желательных
ключевых слов, и материал получает баллы за их наличие.

Почему правила, а не ML:
- Контекст помещения (санузел / кухня / детская) узкий и понятный.
- Экспертные правила прозрачны: видно, почему материал получил балл.
- Работает мгновенно, не требует обучения и разметки.
"""

# ----------------------------------------------------------------------
# ITEM_LABELS: словарь «ключ нормы → (человекочитаемое имя, категория)».
#
# Нужен потому, что в смете материалы называются техническими ключами
# (floor_screed, wallpaper), а скоринг работает с текстом. Этот словарь
# превращает «floor_screed» в «стяжка для пола» — чтобы правило
# «влагостойк» в тексте могло сработать, если это уместно.
# ----------------------------------------------------------------------
ITEM_LABELS = {
    "floor_screed":   ("стяжка для пола", "пол"),
    "floor_tile":     ("керамогранитная плитка для пола влагостойкая нескользящая", "пол"),
    "floor_laminate": ("ламинат для пола износостойкий", "пол"),
    "underlay":       ("подложка под ламинат", "пол"),
    "wall_putty":     ("шпаклёвка для стен", "стены"),
    "wall_primer":    ("грунтовка для стен глубокого проникновения", "стены"),
    "wallpaper":      ("обои для стен флизелиновые влагостойкие моющиеся", "стены"),
    "wall_paint":     ("краска для стен моющаяся водоэмульсионная", "стены"),
    "tile_glue":      ("плиточный клей влагостойкий", "стены"),
    "ceiling_paint":  ("краска для потолка водоэмульсионная", "потолок"),
    "cable":          ("кабель электрический", "электрика"),
    "socket":         ("розетка встраиваемая", "электрика"),
    "switch":         ("выключатель", "электрика"),
    "junction_box":   ("монтажная коробка", "электрика"),
}

# ----------------------------------------------------------------------
# ROOM_RULES: правила скоринга для каждого типа помещения.
#
# require — обязательные ключевые слова. Если найдены в тексте
#           материала — даём +1.0 балла за каждое. Не найденное
#           обязательное слово НЕ штрафует (иначе все материалы
#           получили бы отрицательный score, как было в первой версии).
#
# boost   — желательные ключевые слова. Дают +0.4 за совпадение.
#
# Ключевые слова в нижнем регистре и без окончаний ("влагостойк"),
# чтобы срабатывало на "влагостойкий", "влагостойкая", "влагостойкое".
# ----------------------------------------------------------------------
ROOM_RULES = {
    "санузел":  {"require": ["влагостойк", "плитка", "керамогранит", "нескользящ"],
                 "boost":   ["антигрибок", "влагостойк"]},
    "кухня":    {"require": ["моющ", "термостойк"],
                 "boost":   ["жироотталкивающ", "влагостойк"]},
    "детская":  {"require": ["экологичн", "безопасн"],
                 "boost":   ["гипоаллергенн", "без запаха"]},
    "балкон":   {"require": ["морозостойк", "влагостойк"],
                 "boost":   ["УФ", "влагостойк"]},
    "спальня":  {"require": ["экологичн"], "boost": ["тёпл", "тих"]},
    "гостиная": {"require": [], "boost": ["моющ", "износостойк"]},
}

# ----------------------------------------------------------------------
# score_product: считает балл материала под конкретное помещение.
#
# Args:
#     product: {"name": ..., "description": ...} — текст материала.
#     room_type: "санузел", "кухня", "детская", "балкон", "спальня", "гостиная".
#     humidity: 0..100 — относительная влажность.
#     load: "низкая" | "средняя" | "высокая" — нагрузка на покрытие.
#
# Returns:
#     Число от 0.0 и выше. Чем больше — тем лучше материал подходит.
#     Обычно: 2.0–3.0 — топ, 0.5–1.5 — середина, 0 — не подходит.
# ----------------------------------------------------------------------
def score_product(product: dict, room_type: str, humidity: float, load: str) -> float:
    # Берём правила для указанного помещения (или пусто, если такого нет)
    rules = ROOM_RULES.get(room_type, {})

    # Склеиваем название и описание в один текст для поиска по ключевым словам
    text = (product.get("name", "") + " " + product.get("description", "")).lower()

    score = 0.0

    # --- Обязательные ключевые слова: +1.0 балл за каждое совпадение ---
    # Если чего-то обязательного нет — просто не получаем балл.
    # Раньше здесь был штраф -0.5, из-за чего все материалы для санузла
    # получали score = -2.0 (у сметы нет слова «керамогранит» в ключе).
    for kw in rules.get("require", []):
        if kw.lower() in text:
            score += 1.0

    # --- Желательные ключевые слова: +0.4 балла за совпадение ---
    for kw in rules.get("boost", []):
        if kw.lower() in text:
            score += 0.4

    # --- Бонус за влагостойкость при высокой влажности ---
    # Санузел с влажностью 80% — критично, чтобы материал был влагостойким.
    if humidity > 70 and "влагостойк" in text:
        score += 0.8

    # --- Бонус за прочность при высокой нагрузке ---
    # Для пола в гостиной, где ходят много, важна износостойкость.
    if load == "высокая" and ("усиленн" in text or "износостойк" in text):
        score += 0.6

    # Округляем до 3 знаков — иначе float даёт длинные хвосты
    return round(score, 3)


# ----------------------------------------------------------------------
# label_for: возвращает человекочитаемое имя и категорию для ключа нормы.
#
# Пример: label_for("floor_tile") → ("керамогранитная плитка ...", "пол")
#
# Если ключа нет в словаре (новая норма) — возвращает сам ключ
# и категорию "прочее".
# ----------------------------------------------------------------------
def label_for(item_key: str) -> tuple:
    return ITEM_LABELS.get(item_key, (item_key, "прочее"))